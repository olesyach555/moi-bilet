-- Процедура логирования
CREATE PROCEDURE sp_ЗаписатьОшибку
    @ТипОшибки NVARCHAR(100),
    @СообщениеОб NVARCHAR(MAX),
    @ТрассировкаСтека NVARCHAR(MAX) = NULL,
    @Пользователь NVARCHAR(255) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO dbo.ЛогОшибок (ТипОшибки, СообщениеОб, ТрассировкаСтека, Пользователь)
