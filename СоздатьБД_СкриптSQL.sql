-- 5. СОЗДАНИЕ ХРАНИМЫХ ПРОЦЕДУР
-- ============================================================

-- 5.1 Получить все объекты
CREATE PROCEDURE sp_ПолучитьВсеОбъекты
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        ИДентификатор,
        Наименование,
        Описание,
        Статус,
        ДатаСоздания,
        ДатаИзменения,
        Примечания
    FROM dbo.ОсновныеОбъекты
    ORDER BY ДатаСоздания DESC;
END;

-- 5.2 Получить объект по ID
CREATE PROCEDURE sp_ПолучитьОбъектПоИД
    @ИДентификатор INT
AS
BEGIN
    SET NOCOUNT ON;

    IF @ИДентификатор <= 0
    BEGIN
        RAISERROR(N'ИДентификатор должен быть больше 0', 16, 1);
        RETURN;
    END;

    SELECT
        ИДентификатор,
        Наименование,
        Описание,
        Статус,
        ДатаСоздания,
        ДатаИзменения,
        Примечания
    FROM dbo.ОсновныеОбъекты
    WHERE ИДентификатор = @ИДентификатор;
END;

-- 5.3 Вставить новый объект
CREATE PROCEDURE sp_ВставитьОбъект
    @Наименование NVARCHAR(255),
    @Описание NVARCHAR(MAX) = NULL,
    @Статус NVARCHAR(50) = N'Активно',
    @Примечания NVARCHAR(MAX) = NULL,
    @НовыйИД INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        -- Валидация
        IF @Наименование IS NULL OR LEN(RTRIM(@Наименование)) = 0
        BEGIN
            RAISERROR(N'Наименование обязательно для заполнения', 16, 1);
            RETURN;
        END;

        -- Проверка уникальности
        IF EXISTS (SELECT 1 FROM dbo.ОсновныеОбъекты WHERE Наименование = @Наименование)
        BEGIN
            RAISERROR(N'Объект с таким наименованием уже существует', 16, 1);
            RETURN;
        END;

        -- Вставка
        INSERT INTO dbo.ОсновныеОбъекты
            (Наименование, Описание, Статус, ДатаСоздания, ДатаИзменения, Примечания)
        VALUES
            (@Наименование, @Описание, @Статус, GETDATE(), GETDATE(), @Примечания);

        SET @НовыйИД = SCOPE_IDENTITY();
    END TRY
    BEGIN CATCH
        -- Обработка ошибок
        DECLARE @ОшибкаСообщение NVARCHAR(4000) = ERROR_MESSAGE();
        RAISERROR(@ОшибкаСообщение, 16, 1);
    END CATCH;
END;

-- 5.4 Обновить объект
CREATE PROCEDURE sp_ОбновитьОбъект
    @ИДентификатор INT,
    @Наименование NVARCHAR(255),
    @Описание NVARCHAR(MAX) = NULL,
    @Статус NVARCHAR(50) = NULL,
    @Примечания NVARCHAR(MAX) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        -- Валидация
        IF @ИДентификатор <= 0
        BEGIN
            RAISERROR(N'Некорректный ИДентификатор', 16, 1);
            RETURN;
        END;

        IF @Наименование IS NULL OR LEN(RTRIM(@Наименование)) = 0
        BEGIN
            RAISERROR(N'Наименование обязательно для заполнения', 16, 1);
            RETURN;
        END;

        -- Проверка существования объекта
        IF NOT EXISTS (SELECT 1 FROM dbo.ОсновныеОбъекты WHERE ИДентификатор = @ИДентификатор)
        BEGIN
            RAISERROR(N'Объект не найден', 16, 1);
            RETURN;
        END;

        -- Проверка уникальности нового наименования (если изменяется)
        IF EXISTS (SELECT 1 FROM dbo.ОсновныеОбъекты
                   WHERE Наименование = @Наименование AND ИДентификатор <> @ИДентификатор)
        BEGIN
            RAISERROR(N'Объект с таким наименованием уже существует', 16, 1);
            RETURN;
        END;

        -- Обновление
        UPDATE dbo.ОсновныеОбъекты
        SET
            Наименование = @Наименование,
            Описание = ISNULL(@Описание, Описание),
            Статус = ISNULL(@Статус, Статус),
            Примечания = ISNULL(@Примечания, Примечания),
            ДатаИзменения = GETDATE()
        WHERE ИДентификатор = @ИДентификатор;

    END TRY
    BEGIN CATCH
        DECLARE @ОшибкаСообщение NVARCHAR(4000) = ERROR_MESSAGE();
        RAISERROR(@ОшибкаСообщение, 16, 1);
    END CATCH;
END;

-- 5.5 Удалить объект
CREATE PROCEDURE sp_УдалитьОбъект
    @ИДентификатор INT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        -- Валидация
        IF @ИДентификатор <= 0
        BEGIN
            RAISERROR(N'Некорректный ИДентификатор', 16, 1);
            RETURN;
        END;

        -- Проверка существования объекта
        IF NOT EXISTS (SELECT 1 FROM dbo.ОсновныеОбъекты WHERE ИДентификатор = @ИДентификатор)
        BEGIN
            RAISERROR(N'Объект не найден', 16, 1);
            RETURN;
        END;

        -- Удаление
        DELETE FROM dbo.ОсновныеОбъекты
        WHERE ИДентификатор = @ИДентификатор;

    END TRY
    BEGIN CATCH
        DECLARE @ОшибкаСообщение NVARCHAR(4000) = ERROR_MESSAGE();
        RAISERROR(@ОшибкаСообщение, 16, 1);
    END CATCH;
END;

-- 5.6 Поиск объектов
CREATE PROCEDURE sp_ПоискОбъектов
    @ПоискПоНаименованию NVARCHAR(255) = NULL,
    @Статус NVARCHAR(50) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        ИДентификатор,
        Наименование,
        Описание,
        Статус,
        ДатаСоздания,
        ДатаИзменения,
        Примечания
    FROM dbo.ОсновныеОбъекты
    WHERE
        (
            @ПоискПоНаименованию IS NULL
            OR Наименование LIKE N'%' + @ПоискПоНаименованию + N'%'
        )
        AND
        (
            @Статус IS NULL
            OR Статус = @Статус
        )
    ORDER BY ДатаСоздания DESC;
END;

-- 5.7 Получить количество объектов
CREATE PROCEDURE sp_ПолучитьКоличествоОбъектов
    @Количество INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT @Количество = COUNT(*) FROM dbo.ОсновныеОбъекты;
END;

-- 6. СОЗДАНИЕ ПРЕДСТАВЛЕНИЙ (VIEWS)
-- ============================================================

-- Представление для получения объектов с названием статуса из справочника
CREATE VIEW vw_ОбъектыСоСправочниками
AS
SELECT
    о.ИДентификатор,
    о.Наименование,
    о.Описание,
    о.Статус,
    с.Описание AS ОписаниеСтатуса,
    о.ДатаСоздания,
    о.ДатаИзменения,
    о.Примечания
FROM dbo.ОсновныеОбъекты о
LEFT JOIN dbo.СправочникСтатусы с ON о.Статус = с.Наименование;

