-- 3. СОЗДАНИЕ ОСНОВНОЙ ТАБЛИЦЫ
-- ============================================================
-- Эта таблица служит шаблоном для всех предметных областей
-- При адаптации под конкретную задачу нужно:
-- 1. Переименовать таблицу (например: Адвокаты, Заповедники и т.д.)
-- 2. Добавить специфичные для задачи поля
-- 3. Создать справочные таблицы для связанных сущностей

CREATE TABLE dbo.ОсновныеОбъекты (
    ИДентификатор INT PRIMARY KEY IDENTITY(1,1),

    -- Основные поля (обязательные для всех задач)
    Наименование NVARCHAR(255) NOT NULL UNIQUE,
    Описание NVARCHAR(MAX),

    -- Статус и отслеживание
    Статус NVARCHAR(50) DEFAULT N'Активно' NOT NULL,

    -- Даты
    ДатаСоздания DATETIME DEFAULT GETDATE() NOT NULL,
    ДатаИзменения DATETIME DEFAULT GETDATE() NOT NULL,

    -- Примечания
    Примечания NVARCHAR(MAX),

    -- Внешний ключ на справочник статусов (опционально)
    CONSTRAINT FK_Статусы FOREIGN KEY (Статус)
        REFERENCES dbo.СправочникСтатусы(Наименование)
);

